#!/usr/bin/env node
// lyricreel CLI — song + lyrics → procedural lyric music video
const fs = require('fs'), path = require('path'), http = require('http');
const { spawnSync, spawn } = require('child_process');

const ROOT = path.resolve(__dirname, '..');
const ENGINE = path.join(ROOT, 'engine');
const argv = process.argv.slice(2);
const cmd = argv[0];
const opt = (k, d) => { const i = argv.indexOf(k); return i >= 0 && argv[i + 1] !== undefined ? argv[i + 1] : d; };
const flag = k => argv.includes(k);
const VALUED = new Set(['--audio', '--title', '--artist', '--model', '--lang', '--refine', '--port', '--out', '--from', '--to', '--fps', '--crf', '--scene', '--t']);
const positional = argv.slice(1).filter((a, i, arr) => !a.startsWith('--') && !(i > 0 && VALUED.has(arr[i - 1])));

const HELP = `lyricreel — turn a song + lyrics into a procedural lyric music video

Usage: lyricreel <command> [project-dir] [options]

  new <dir> [--audio song.mp3] [--title T] [--artist A]   create a project folder
  analyze <dir>                  beats / BPM / energy       → build/audio.json
  transcribe <dir> [--model small] [--lang en] [--refine 0-20,130-160]
                                 Whisper word timestamps    → build/asr.json
  align <dir>                    script.txt × ASR           → build/timeline.js
  build <dir> [--no-asr]         analyze + transcribe + align
  preview <dir> [--port 8123]    play it in the browser with audio
  stills <dir> <t1,t2,…> [--out dir]   export frames (JPEG) at given seconds
  render <dir> [--from s] [--to s] [--fps 30] [--crf 20] [--out file.mp4]
  scenes [--md]                  list the scene library (--md writes docs/SCENES.md)
  gallery [--out docs/gallery.jpg] [--scene name]   contact sheet of every scene

Env: LYRICREEL_PYTHON (python with requirements.txt), CHROME_PATH (Chrome/Chromium binary)`;

function die(msg) { console.error('✗ ' + msg); process.exit(1); }
function projectDir() {
  const d = positional[0];
  if (!d) die('missing project directory');
  const abs = path.resolve(d);
  if (cmd !== 'new' && !fs.existsSync(path.join(abs, 'project.json'))) die(`${abs} has no project.json`);
  return abs;
}
function python() {
  if (process.env.LYRICREEL_PYTHON) return process.env.LYRICREEL_PYTHON;
  for (const p of ['.venv/bin/python', 'venv/bin/python']) if (fs.existsSync(path.join(ROOT, p))) return path.join(ROOT, p);
  return 'python3';
}
function py(script, args) {
  const r = spawnSync(python(), [path.join(ROOT, 'pipeline', script), ...args], { stdio: 'inherit', cwd: path.join(ROOT, 'pipeline') });
  if (r.status !== 0) die(`${script} failed`);
}
function chromePath() {
  if (process.env.CHROME_PATH) return process.env.CHROME_PATH;
  const c = ['/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', '/Applications/Chromium.app/Contents/MacOS/Chromium',
    '/usr/bin/google-chrome', '/usr/bin/google-chrome-stable', '/usr/bin/chromium', '/usr/bin/chromium-browser',
    'C:\\Program Files\\Google\\Chrome\\Application\\chrome.exe'];
  const f = c.find(p => fs.existsSync(p));
  if (!f) die('Chrome not found — set CHROME_PATH');
  return f;
}
// 掃描 engine/scenes/*.js → manifest.js（新增場景檔後不用手動登記）
function writeManifest() {
  const files = fs.readdirSync(path.join(ENGINE, 'scenes')).filter(f => f.endsWith('.js') && f !== 'manifest.js').sort();
  fs.writeFileSync(path.join(ENGINE, 'scenes', 'manifest.js'),
    '// generated by lyricreel — lists engine/scenes/*.js\nwindow.LR_ENGINE_SCENES = ' + JSON.stringify(files) + ';\n');
}
function sceneList() {
  writeManifest();
  return fs.readdirSync(path.join(ENGINE, 'scenes')).filter(f => f.endsWith('.js') && f !== 'manifest.js').sort().map(f => {
    const src = fs.readFileSync(path.join(ENGINE, 'scenes', f), 'utf8');
    const m = src.match(/scene\('([^']+)',\s*(\{.*?\})\s*,\s*s\s*=>/s);
    return m ? { name: m[1], ...JSON.parse(m[2]) } : { name: f.replace('.js', '') };
  });
}

async function browser() {
  writeManifest();
  let puppeteer;
  try { puppeteer = require('puppeteer-core'); } catch { die('run `npm install` first'); }
  const b = await puppeteer.launch({ executablePath: chromePath(), headless: 'new',
    args: ['--allow-file-access-from-files', '--disable-web-security', '--force-device-scale-factor=1'] });
  const page = await b.newPage();
  await page.setViewport({ width: 1920, height: 1080 });
  page.on('console', m => { if (['warn', 'error'].includes(m.type())) console.log('[page]', m.text()); });
  page.on('pageerror', e => console.log('[page error]', e.message));
  return { b, page };
}
async function openProject(page, pdir) {
  const url = 'file://' + path.join(ENGINE, 'player.html') + '?project=' + encodeURIComponent('file://' + pdir);
  await page.goto(url);
  await page.evaluate(() => window.lrReady);
}
const grab = (page, t, q = 0.93) => page.evaluate((t, q) => { renderAt(t); return document.getElementById('c').toDataURL('image/jpeg', q).split(',')[1]; }, t, q);

function requireTimeline(pdir) {
  if (!fs.existsSync(path.join(pdir, 'build', 'timeline.js'))) die('no build/timeline.js — run `lyricreel build` (or align) first');
}

const commands = {
  help() { console.log(HELP); },

  new() {
    const pdir = projectDir();
    if (fs.existsSync(path.join(pdir, 'project.json'))) die(`${pdir} already has a project.json`);
    fs.mkdirSync(path.join(pdir, 'scenes'), { recursive: true });
    const audio = opt('--audio');
    let audioName = 'song.mp3';
    if (audio) { audioName = 'song' + path.extname(audio); fs.copyFileSync(path.resolve(audio), path.join(pdir, audioName)); }
    const title = opt('--title', path.basename(pdir).toUpperCase());
    fs.writeFileSync(path.join(pdir, 'project.json'), JSON.stringify({
      title, artist: opt('--artist', ''), audio: audioName,
      whisper: { model: 'small', language: null, refine: [] }
    }, null, 2) + '\n');
    fs.writeFileSync(path.join(pdir, 'script.txt'), `# section | scene[:arg] | lyric (ad-libs in parentheses) | @start (optional)
# section: intro / verse1 / pre1 / chorus1 / post1 / bridge / outro …  (empty = same as previous line)
# scene:   run \`lyricreel scenes\` for the library; empty = typo
# @start:  pin a line's start in seconds when auto-alignment gets it wrong

intro   | title          | First line of the song
verse1  | typo           | Second line goes here
chorus1 | typo:HOOK      | The hook line (hook!)
`);
    fs.writeFileSync(path.join(pdir, '.gitignore'), 'build/\nout/\n');
    console.log(`✓ created ${pdir}\n  next: put your audio in ${audioName}${audio ? ' (done)' : ''}, write script.txt, then \`lyricreel build ${positional[0]}\``);
  },

  analyze() { py('analyze.py', [projectDir()]); },
  transcribe() {
    const a = [projectDir()];
    for (const k of ['--model', '--lang', '--refine']) if (opt(k)) a.push(k, opt(k));
    py('transcribe.py', a);
  },
  align() { py('align.py', [projectDir()]); },
  build() {
    const pdir = projectDir();
    py('analyze.py', [pdir]);
    if (!flag('--no-asr')) { const a = [pdir]; for (const k of ['--model', '--lang', '--refine']) if (opt(k)) a.push(k, opt(k)); py('transcribe.py', a); }
    py('align.py', [pdir]);
  },

  preview() {
    const pdir = projectDir(); requireTimeline(pdir); writeManifest();
    const port = +opt('--port', 8123);
    const types = { '.html': 'text/html', '.js': 'text/javascript', '.ttf': 'font/ttf', '.mp3': 'audio/mpeg', '.wav': 'audio/wav', '.m4a': 'audio/mp4', '.json': 'application/json' };
    http.createServer((req, res) => { try {
      const u = decodeURIComponent(req.url.split('?')[0]);
      const [base, rel] = u.startsWith('/project/') ? [pdir, u.slice(9)] : [ENGINE, u.slice(1) || 'player.html'];
      const f = path.join(base, rel);
      if (!(f + path.sep).startsWith(base + path.sep) || !fs.existsSync(f) || fs.statSync(f).isDirectory()) { res.writeHead(404); return res.end('not found'); }
      const size = fs.statSync(f).size, range = req.headers.range, type = types[path.extname(f)] || 'application/octet-stream';
      const m = range && /^bytes=(\d*)-(\d*)$/.exec(range.trim());
      if (m && (m[1] || m[2])) { // 讓瀏覽器可以拖曳音訊
        let start = m[1] ? +m[1] : Math.max(0, size - +m[2]), end = m[1] && m[2] ? Math.min(+m[2], size - 1) : size - 1;
        if (start > end || start >= size) { res.writeHead(416, { 'Content-Range': `bytes */${size}` }); return res.end(); }
        res.writeHead(206, { 'Content-Type': type, 'Content-Range': `bytes ${start}-${end}/${size}`, 'Accept-Ranges': 'bytes', 'Content-Length': end - start + 1 });
        return fs.createReadStream(f, { start, end }).pipe(res);
      }
      res.writeHead(200, { 'Content-Type': type, 'Content-Length': size, 'Accept-Ranges': 'bytes' });
      fs.createReadStream(f).pipe(res);
    } catch (e) { console.error('[preview]', e.message); if (!res.headersSent) res.writeHead(500); res.end(); } }).listen(port, () => console.log(`▶ http://localhost:${port}/player.html?project=/project&preview   (Ctrl+C to stop)`));
  },

  async stills() {
    const pdir = projectDir(); requireTimeline(pdir);
    const times = (positional[1] || '').split(',').filter(Boolean).map(Number);
    if (!times.length) die('give times in seconds, e.g. `lyricreel stills my-song 8,21.5,60`');
    const out = path.resolve(opt('--out', path.join(pdir, 'out', 'stills')));
    fs.mkdirSync(out, { recursive: true });
    const { b, page } = await browser(); await openProject(page, pdir);
    for (const t of times) {
      const f = path.join(out, `t${t.toFixed(2).padStart(6, '0')}.jpg`);
      fs.writeFileSync(f, Buffer.from(await grab(page, t), 'base64')); console.log(f);
    }
    await b.close();
  },

  async render() {
    const pdir = projectDir(); requireTimeline(pdir);
    const cfg = JSON.parse(fs.readFileSync(path.join(pdir, 'project.json'), 'utf8'));
    const fps = +opt('--fps', cfg.fps || 30), crf = opt('--crf', '20');
    const { b, page } = await browser(); await openProject(page, pdir);
    const dur = await page.evaluate(() => AU.dur);
    const from = +opt('--from', 0), to = Math.min(+opt('--to', dur), dur);
    const name = (cfg.title || path.basename(pdir)).replace(/[^\w\-]+/g, '_');
    const outFile = path.resolve(opt('--out', path.join(pdir, 'out', from === 0 && to === dur ? `${name}.mp4` : `${name}_${from}-${to}.mp4`)));
    fs.mkdirSync(path.dirname(outFile), { recursive: true });
    const ff = spawn('ffmpeg', ['-y', '-loglevel', 'error', '-f', 'image2pipe', '-framerate', String(fps), '-c:v', 'mjpeg', '-i', '-',
      '-ss', String(from), '-t', String(to - from), '-i', path.join(pdir, cfg.audio || 'song.mp3'),
      '-map', '0:v', '-map', '1:a', '-c:v', 'libx264', '-preset', 'medium', '-crf', String(crf), '-pix_fmt', 'yuv420p',
      '-c:a', 'aac', '-b:a', '256k', '-shortest', '-movflags', '+faststart', outFile], { stdio: ['pipe', 'inherit', 'inherit'] });
    const n = Math.round((to - from) * fps), t0 = Date.now();
    for (let f = 0; f < n; f++) {
      const buf = Buffer.from(await grab(page, from + f / fps), 'base64');
      if (!ff.stdin.write(buf)) await new Promise(r => ff.stdin.once('drain', r));
      if (f % 150 === 0 || f === n - 1) process.stdout.write(`\rframe ${f + 1}/${n}  ${((Date.now() - t0) / 1000).toFixed(0)}s   `);
    }
    ff.stdin.end(); const code = await new Promise(r => ff.on('close', r));
    await b.close();
    if (code !== 0) die('ffmpeg failed');
    console.log(`\n✓ ${outFile}`);
  },

  scenes() {
    if (flag('--md')) {   // 產生 docs/SCENES.md
      const rows = sceneList().map(s => `| \`${s.name}\` | ${s.desc || ''} | ${s.fits || ''} | ${s.arg || '—'} |`);
      const md = `# Scene library\n\nGenerated by \`lyricreel scenes --md\`. Contact sheet: [gallery.jpg](gallery.jpg) (same order, left→right, top→bottom).\n\n` +
        `Use a scene in \`script.txt\` as \`name\` or \`name:ARG\`.\n\n| scene | what you see | fits lyrics about | arg |\n|---|---|---|---|\n${rows.join('\n')}\n`;
      fs.writeFileSync(path.join(ROOT, 'docs', 'SCENES.md'), md); return console.log('✓ docs/SCENES.md');
    }
    for (const s of sceneList()) console.log(`${s.name.padEnd(12)} ${s.desc || ''}\n${''.padEnd(12)} fits: ${s.fits || '-'}${s.arg ? `\n${''.padEnd(12)} arg:  ${s.arg}` : ''}\n`);
  },

  async gallery() {
    const only = opt('--scene');
    const list = sceneList().filter(s => !only || s.name === only);
    const out = path.resolve(opt('--out', path.join(ROOT, 'docs', only ? `scene-${only}.jpg` : 'gallery.jpg')));
    const tmp = fs.mkdtempSync(path.join(require('os').tmpdir(), 'lyricreel-'));
    const { b, page } = await browser();
    await page.goto('file://' + path.join(ENGINE, 'player.html'));
    await page.evaluate(() => window.lrReady);
    for (const [i, s] of list.entries()) {
      await page.evaluate(n => lrDemo(n), s.name);
      const jpg = Buffer.from(await grab(page, +opt('--t', 2.4)), 'base64');
      fs.writeFileSync(path.join(tmp, `${String(i).padStart(3, '0')}.jpg`), jpg);
    }
    await b.close();
    fs.mkdirSync(path.dirname(out), { recursive: true });
    if (list.length === 1) { fs.copyFileSync(path.join(tmp, '000.jpg'), out); }
    else {
      const cols = 4, rows = Math.ceil(list.length / cols);
      // 場景名稱依序列在 docs/SCENES.md（不用 drawtext：部分 ffmpeg 沒編進 freetype）
      const r = spawnSync('ffmpeg', ['-y', '-loglevel', 'error', '-pattern_type', 'glob', '-i', path.join(tmp, '*.jpg'),
        '-vf', `scale=480:270,tile=${cols}x${rows}:padding=6:color=0x1b0a24`, '-frames:v', '1', '-q:v', '3', out], { stdio: 'inherit' });
      if (r.status !== 0) die('ffmpeg tile failed');
    }
    console.log(`✓ ${out}  (${list.length} scenes: ${list.map(s => s.name).join(', ')})`);
  },
};

(async () => {
  if (!cmd || ['-h', '--help', 'help'].includes(cmd)) return commands.help();
  if (!commands[cmd]) die(`unknown command "${cmd}"\n\n${HELP}`);
  await commands[cmd]();
})().catch(e => die(e.stack || e.message));
